import { StaticGazetteer, type GazetteerEntry, type PlaceKind } from './gazetteer.js';

/**
 * Built-in gazetteer: a small, static, offline fallback (countries, US states, major
 * cities, Hawaiian islands/places, major airports by IATA/ICAO). The full PlaceIndex
 * (a separate package) is composed in front of it at runtime. Coordinates are
 * approximate centroids; bounds are coarse bounding boxes for "over X"/"in X".
 */
type Bounds = [west: number, south: number, east: number, north: number];

function country(
  code: string,
  name: string,
  lat: number,
  lon: number,
  b: Bounds,
  aliases: string[] = [],
): GazetteerEntry {
  return {
    id: `iso3166-1:${code}`,
    name,
    kind: 'country',
    position: { latitude: lat, longitude: lon },
    bounds: { west: b[0], south: b[1], east: b[2], north: b[3] },
    countryCode: code,
    ...(aliases.length ? { aliases } : {}),
  };
}
function state(
  code: string,
  name: string,
  lat: number,
  lon: number,
  b: Bounds,
  kind: PlaceKind = 'region',
  aliases: string[] = [],
): GazetteerEntry {
  return {
    id: `iso3166-2:US-${code}`,
    name,
    kind,
    position: { latitude: lat, longitude: lon },
    bounds: { west: b[0], south: b[1], east: b[2], north: b[3] },
    countryCode: 'US',
    ...(aliases.length ? { aliases } : {}),
  };
}
function place(
  slug: string,
  name: string,
  kind: PlaceKind,
  lat: number,
  lon: number,
  cc: string,
  aliases: string[] = [],
  b?: Bounds,
): GazetteerEntry {
  return {
    id: `place:builtin:${slug}`,
    name,
    kind,
    position: { latitude: lat, longitude: lon },
    countryCode: cc,
    ...(aliases.length ? { aliases } : {}),
    ...(b ? { bounds: { west: b[0], south: b[1], east: b[2], north: b[3] } } : {}),
  };
}
function airport(
  iata: string,
  icao: string,
  name: string,
  lat: number,
  lon: number,
  cc: string,
  aliases: string[] = [],
): GazetteerEntry {
  return {
    id: `airport:iata:${iata}`,
    name,
    kind: 'airport',
    position: { latitude: lat, longitude: lon },
    countryCode: cc,
    aliases: [iata, icao, ...aliases],
  };
}

